"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";

import { MAX_AVAILABILITY_RULES, parseAvailabilityRules, type RuleIssue } from "@/domain/booking/availability";
import { EVENT_TYPE_FIELDS, parseEventTypeDraft, type EventTypeDraft } from "@/domain/booking/event-type";
import { err, ok, type Result } from "@/domain/shared/result";
import { textFields } from "@/server/actions/form-fields";
import {
  availabilityRulesSchema,
  booleanFieldSchema,
  bookingIdSchema,
  eventTypeOrderSchema,
  integerField,
  jsonField,
} from "@/server/booking/action-schemas";
import type { AddAvailabilityExceptionError } from "@/server/booking/use-cases/add-availability-exception";
import { createContainer } from "@/server/container";

export type BookingSettingsActionError =
  | "invalid_input"
  | "not_found"
  | "rate_limited"
  | "limit_reached"
  | "has_bookings"
  | "overlap"
  | "conflict"
  | "invalid_range"
  | "already_ended"
  | "unexpected";

export type BookingSettingsState =
  | { status: "idle" }
  | { status: "saved" }
  | { status: "error"; error: BookingSettingsActionError; fields?: string[]; ruleIssues?: RuleIssue[] };

const SETTINGS_PATH = "/tableau-de-bord/rendez-vous/reglages";
const SIGN_IN_PATH = "/connexion";
const SAVED: BookingSettingsState = { status: "saved" };

const EVENT_TYPE_FORM_FIELDS = ["id", ...EVENT_TYPE_FIELDS] as const;

function invalidInput(fields: string[]): BookingSettingsState {
  return { status: "error", error: "invalid_input", fields };
}

function asIs(error: BookingSettingsActionError): BookingSettingsState {
  return { status: "error", error };
}

/** "unauthenticated" → sign-in page; success only → the settings page is revalidated. */
function settle<E extends string>(
  result: Result<unknown, E | "unauthenticated">,
  errorState: (error: E) => BookingSettingsState,
): BookingSettingsState {
  if (!result.ok) {
    if (result.error === "unauthenticated") {
      redirect(SIGN_IN_PATH);
    }
    return errorState(result.error as E);
  }
  revalidatePath(SETTINGS_PATH);
  return SAVED;
}

/** Every invalid field in form order (`id` first); never a submitted value. */
function parseEventTypeForm(formData: FormData): Result<EventTypeDraft & { id: string }, string[]> {
  const fields = textFields(formData, EVENT_TYPE_FORM_FIELDS);
  const id = bookingIdSchema.safeParse(fields.id);
  const draft = parseEventTypeDraft({
    title: fields.title ?? "",
    durationMin: integerField(fields.durationMin),
    bufferMin: integerField(fields.bufferMin),
    minNoticeMin: integerField(fields.minNoticeMin),
    locationKind: fields.locationKind ?? "",
    locationText: fields.locationText ?? null,
  });
  if (!id.success || !draft.ok) {
    return err([...(id.success ? [] : ["id"]), ...(draft.ok ? [] : draft.error)]);
  }
  return ok({ id: id.data, ...draft.value });
}

function parseIdField(formData: FormData): string | null {
  const id = bookingIdSchema.safeParse(textFields(formData, ["id"]).id);
  return id.success ? id.data : null;
}

/** Field `timeZone`, validated by the use case (`parseSelectableTimeZone`). */
export async function saveTimeZoneAction(_previous: BookingSettingsState, formData: FormData): Promise<BookingSettingsState> {
  const { timeZone } = textFields(formData, ["timeZone"]);
  const { saveTimeZone } = await createContainer();
  return settle(await saveTimeZone(timeZone ?? ""), (error) =>
    error === "invalid_input" ? invalidInput(["timeZone"]) : asIs(error),
  );
}

/**
 * Fields of the editor; `id` is generated by the Server Component and passed to the form as a hidden field
 * (idempotency key of the creation; a new one after `saved`, through `revalidatePath`).
 */
export async function createEventTypeAction(_previous: BookingSettingsState, formData: FormData): Promise<BookingSettingsState> {
  const command = parseEventTypeForm(formData);
  if (!command.ok) {
    return invalidInput(command.error);
  }
  const { createEventType } = await createContainer();
  return settle(await createEventType(command.value), asIs);
}

export async function updateEventTypeAction(_previous: BookingSettingsState, formData: FormData): Promise<BookingSettingsState> {
  const command = parseEventTypeForm(formData);
  if (!command.ok) {
    return invalidInput(command.error);
  }
  const { updateEventType } = await createContainer();
  return settle(await updateEventType(command.value), asIs);
}

/** Fields `id` and `isActive` ("true" | "false"). */
export async function setEventTypeActiveAction(
  _previous: BookingSettingsState,
  formData: FormData,
): Promise<BookingSettingsState> {
  const id = parseIdField(formData);
  const isActive = booleanFieldSchema.safeParse(textFields(formData, ["isActive"]).isActive);
  if (id === null || !isActive.success) {
    return invalidInput([...(id === null ? ["id"] : []), ...(isActive.success ? [] : ["isActive"])]);
  }
  const { setEventTypeActive } = await createContainer();
  return settle(await setEventTypeActive({ id, isActive: isActive.data }), asIs);
}

/** Field `ids`: JSON array, the full order of the caller's types. */
export async function reorderEventTypesAction(
  _previous: BookingSettingsState,
  formData: FormData,
): Promise<BookingSettingsState> {
  const ids = eventTypeOrderSchema.safeParse(jsonField(textFields(formData, ["ids"]).ids));
  if (!ids.success) {
    return invalidInput(["ids"]);
  }
  const { reorderEventTypes } = await createContainer();
  return settle(await reorderEventTypes(ids.data), asIs);
}

/** Field `id`; a type with bookings answers `has_bookings` (to be deactivated instead). Replayable. */
export async function deleteEventTypeAction(_previous: BookingSettingsState, formData: FormData): Promise<BookingSettingsState> {
  const id = parseIdField(formData);
  if (id === null) {
    return invalidInput(["id"]);
  }
  const { deleteEventType } = await createContainer();
  return settle(await deleteEventType(id), asIs);
}

/**
 * Field `rules`: JSON array of `{ weekday, start, end }`, the whole weekly list. More than 50 elements →
 * `limit_reached`, whatever they are, before any element is parsed.
 */
export async function replaceAvailabilityRulesAction(
  _previous: BookingSettingsState,
  formData: FormData,
): Promise<BookingSettingsState> {
  const raw = jsonField(textFields(formData, ["rules"]).rules);
  if (Array.isArray(raw) && raw.length > MAX_AVAILABILITY_RULES) {
    return asIs("limit_reached");
  }
  const shape = availabilityRulesSchema.safeParse(raw);
  if (!shape.success) {
    return invalidInput(["rules"]);
  }
  const rules = parseAvailabilityRules(shape.data);
  if (!rules.ok) {
    return rules.error === "too_many"
      ? asIs("limit_reached")
      : { status: "error", error: "invalid_input", ruleIssues: rules.error };
  }
  const { replaceAvailabilityRules } = await createContainer();
  return settle(await replaceAvailabilityRules(rules.value), asIs);
}

function exceptionErrorState(error: Exclude<AddAvailabilityExceptionError, "unauthenticated">): BookingSettingsState {
  switch (error) {
    case "invalid_kind":
      return invalidInput(["kind"]);
    case "invalid_start":
      return invalidInput(["start"]);
    case "invalid_end":
      return invalidInput(["end"]);
    case "invalid_range":
    case "already_ended":
      return { status: "error", error, fields: ["end"] };
    default:
      return asIs(error);
  }
}

/**
 * Fields `id` (idempotency key, generated by the Server Component as for the types), `kind`, `start` and `end`
 * (`datetime-local`, read in the profile's time zone).
 */
export async function addAvailabilityExceptionAction(
  _previous: BookingSettingsState,
  formData: FormData,
): Promise<BookingSettingsState> {
  const id = parseIdField(formData);
  if (id === null) {
    return invalidInput(["id"]);
  }
  const { kind, start, end } = textFields(formData, ["kind", "start", "end"]);
  const { addAvailabilityException } = await createContainer();
  return settle(
    await addAvailabilityException({ id, kind: kind ?? "", start: start ?? "", end: end ?? "" }),
    exceptionErrorState,
  );
}

/** Field `id`. Replayable. */
export async function removeAvailabilityExceptionAction(
  _previous: BookingSettingsState,
  formData: FormData,
): Promise<BookingSettingsState> {
  const id = parseIdField(formData);
  if (id === null) {
    return invalidInput(["id"]);
  }
  const { removeAvailabilityException } = await createContainer();
  return settle(await removeAvailabilityException(id), asIs);
}
