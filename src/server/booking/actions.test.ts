type ActionName = Exclude<keyof typeof import("@/server/booking/actions"), "default">;

/** Every action with a valid form and the use case it must call. */
const VALID: ReadonlyArray<readonly [ActionName, keyof typeof mocks, () => FormData]> = [
  ["saveTimeZoneAction", "saveTimeZone", () => form({ timeZone: "Asia/Tokyo" })],
  ["createEventTypeAction", "createEventType", () => form(EVENT_TYPE_FORM)],
  ["updateEventTypeAction", "updateEventType", () => form({ ...EVENT_TYPE_FORM, id: EVENT_TYPE_IDS[0] })],
  ["setEventTypeActiveAction", "setEventTypeActive", () => form({ id: EVENT_TYPE_IDS[0], isActive: "false" })],
  ["reorderEventTypesAction", "reorderEventTypes", () => form({ ids: JSON.stringify([EVENT_TYPE_IDS[1], EVENT_TYPE_IDS[0]]) })],
  ["deleteEventTypeAction", "deleteEventType", () => form({ id: EVENT_TYPE_IDS[0] })],
  ["replaceAvailabilityRulesAction", "replaceAvailabilityRules", () => form({ rules: JSON.stringify(aWorkingWeek()) })],
  ["addAvailabilityExceptionAction", "addAvailabilityException", () => form(anExceptionInput())],
  ["removeAvailabilityExceptionAction", "removeAvailabilityException", () => form({ id: EXCEPTION_IDS[0] })],
];

async function run(name: ActionName, data: FormData): Promise<BookingSettingsState> {
  const action = actions[name] as (previous: BookingSettingsState, formData: FormData) => Promise<BookingSettingsState>;
  return action(IDLE, data);
}

describe("every action (decision 1, ADR 0012)", () => {
  it.each(VALID)("%s: valid form → calls %s once → { status: 'saved' }, then revalidates the settings page", async (name, useCase, data) => {
    expect(await run(name, data())).toStrictEqual({ status: "saved" });

    expect(mocks[useCase]).toHaveBeenCalledTimes(1);
    expect(mocks.revalidatePath).toHaveBeenCalledWith(SETTINGS_PATH);
    expect(mocks[useCase].mock.invocationCallOrder[0]).toBeLessThan(mocks.revalidatePath.mock.invocationCallOrder[0] ?? 0);
  });

  it.each(VALID)("%s: not signed in (use case 'unauthenticated') → redirect('/connexion'), nothing revalidated", async (name, useCase, data) => {
    mocks[useCase].mockResolvedValue(err("unauthenticated"));

    await expect(run(name, data())).rejects.toThrow("NEXT_REDIRECT:/connexion");
    expect(mocks.redirect).toHaveBeenCalledWith("/connexion");
    expect(mocks.revalidatePath).not.toHaveBeenCalled();
  });

  it.each(VALID)("%s: authorization delegated to the use case at every call (createContainer each time)", async (name, _useCase, data) => {
    await run(name, data());
    await run(name, data());

    expect(mocks.createContainer).toHaveBeenCalledTimes(2);
  });

  it.each(VALID)("%s: use case error → { status: 'error', error } as is, nothing revalidated", async (name, useCase, data) => {
    for (const error of ["not_found", "rate_limited", "unexpected"] as const) {
      mocks[useCase].mockResolvedValueOnce(err(error));

      expect(await run(name, data())).toMatchObject({ status: "error", error });
    }
    expect(mocks.revalidatePath).not.toHaveBeenCalled();
  });
});

describe("saveTimeZoneAction", () => {
  it("forwards the submitted zone; the use case validates it", async () => {
    await run("saveTimeZoneAction", form({ timeZone: "Asia/Tokyo" }));

    expect(mocks.saveTimeZone).toHaveBeenCalledWith("Asia/Tokyo");
  });

  it("refused zone (use case invalid_input) → fields ['timeZone'], the value never echoed", async () => {
    mocks.saveTimeZone.mockResolvedValue(err("invalid_input"));

    const state = await run("saveTimeZoneAction", form({ timeZone: "Mars/Olympus" }));

    expect(state).toStrictEqual({ status: "error", error: "invalid_input", fields: ["timeZone"] });
    expect(JSON.stringify(state)).not.toContain("Mars");
  });
});

describe("createEventTypeAction / updateEventTypeAction — criterion 1", () => {
  it("create: parsed command (id lower-cased, title trimmed, numbers converted)", async () => {
    await run("createEventTypeAction", form(EVENT_TYPE_FORM));

    expect(mocks.createEventType).toHaveBeenCalledWith(EVENT_TYPE_COMMAND);
  });

  it("update: the same parsing, with the id of the edited type", async () => {
    await run("updateEventTypeAction", form({ ...EVENT_TYPE_FORM, id: EVENT_TYPE_IDS[0] }));

    expect(mocks.updateEventType).toHaveBeenCalledWith({ ...EVENT_TYPE_COMMAND, id: EVENT_TYPE_IDS[0] });
  });

  it("phone without location text (field absent) → locationText null", async () => {
    await run("createEventTypeAction", form({ ...EVENT_TYPE_FORM, locationKind: "phone", locationText: undefined }));

    expect(mocks.createEventType).toHaveBeenCalledWith({ ...EVENT_TYPE_COMMAND, locationKind: "phone", locationText: null });
  });

  it.each([
    ["a missing id", { id: undefined }, ["id"]],
    ["a malformed id", { id: "not-a-uuid" }, ["id"]],
    ["a blank title", { title: "   " }, ["title"]],
    ["an empty duration", { durationMin: "" }, ["durationMin"]],
    ["a hexadecimal duration", { durationMin: "0x1E" }, ["durationMin"]],
    ["an exponent duration", { durationMin: "3e1" }, ["durationMin"]],
    ["a decimal buffer", { bufferMin: "7.5" }, ["bufferMin"]],
    ["a negative notice", { minNoticeMin: "-1" }, ["minNoticeMin"]],
    ["an unknown location kind", { locationKind: "teams" }, ["locationKind"]],
    ["in person without address", { locationKind: "in_person", locationText: "" }, ["locationText"]],
    ["several faults", { id: "x", title: "", durationMin: "1000" }, ["id", "title", "durationMin"]],
  ])("%s → invalid_input with the fields, before building the container", async (_label, patch, fields) => {
    const state = await run("createEventTypeAction", form({ ...EVENT_TYPE_FORM, ...patch }));

    expect(state).toStrictEqual({ status: "error", error: "invalid_input", fields });
    expect(mocks.createContainer).not.toHaveBeenCalled();
    expect(mocks.revalidatePath).not.toHaveBeenCalled();
  });

  it.each(["limit_reached", "conflict", "invalid_input"] as const)("create: use case %s → { status: 'error', error: %j }", async (error) => {
    mocks.createEventType.mockResolvedValue(err(error));

    expect(await run("createEventTypeAction", form(EVENT_TYPE_FORM))).toMatchObject({ status: "error", error });
  });

  it("the submitted title is never echoed in an error state", async () => {
    const state = await run("createEventTypeAction", form({ ...EVENT_TYPE_FORM, title: `SECRET${"x".repeat(90)}` }));

    expect(JSON.stringify(state)).not.toContain("SECRET");
  });
});

describe("setEventTypeActiveAction, reorderEventTypesAction, deleteEventTypeAction", () => {
  it("isActive 'true' / 'false' → boolean", async () => {
    await run("setEventTypeActiveAction", form({ id: EVENT_TYPE_IDS[0], isActive: "true" }));
    await run("setEventTypeActiveAction", form({ id: EVENT_TYPE_IDS[0], isActive: "false" }));

    expect(mocks.setEventTypeActive.mock.calls).toStrictEqual([
      [{ id: EVENT_TYPE_IDS[0], isActive: true }],
      [{ id: EVENT_TYPE_IDS[0], isActive: false }],
    ]);
  });

  it("isActive outside 'true' / 'false' → invalid_input ['isActive']", async () => {
    expect(await run("setEventTypeActiveAction", form({ id: EVENT_TYPE_IDS[0], isActive: "on" }))).toStrictEqual({
      status: "error",
      error: "invalid_input",
      fields: ["isActive"],
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("reorder: forwards the full order", async () => {
    await run("reorderEventTypesAction", form({ ids: JSON.stringify([EVENT_TYPE_IDS[1], EVENT_TYPE_IDS[0]]) }));

    expect(mocks.reorderEventTypes).toHaveBeenCalledWith([EVENT_TYPE_IDS[1], EVENT_TYPE_IDS[0]]);
  });

  it.each([
    ["not JSON", "[oops"],
    ["not an array", JSON.stringify({ ids: [] })],
    ["empty", JSON.stringify([])],
    ["a non-uuid", JSON.stringify(["abc"])],
    ["eleven ids", JSON.stringify(Array.from({ length: 11 }, () => EVENT_TYPE_IDS[0]))],
  ])("reorder: ids %s → invalid_input ['ids']", async (_label, ids) => {
    expect(await run("reorderEventTypesAction", form({ ids }))).toStrictEqual({ status: "error", error: "invalid_input", fields: ["ids"] });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("reorder: stale list (use case conflict) → error conflict", async () => {
    mocks.reorderEventTypes.mockResolvedValue(err("conflict"));

    expect(await run("reorderEventTypesAction", form({ ids: JSON.stringify([EVENT_TYPE_IDS[0]]) }))).toMatchObject({
      status: "error",
      error: "conflict",
    });
  });

  it("delete: forwards the id; a type with bookings → error has_bookings (the page proposes to deactivate it)", async () => {
    mocks.deleteEventType.mockResolvedValue(err("has_bookings"));

    expect(await run("deleteEventTypeAction", form({ id: EVENT_TYPE_IDS[0] }))).toStrictEqual({ status: "error", error: "has_bookings" });
    expect(mocks.deleteEventType).toHaveBeenCalledWith(EVENT_TYPE_IDS[0]);
  });

  it.each(["deleteEventTypeAction", "removeAvailabilityExceptionAction"] as const)("%s: malformed id → invalid_input ['id']", async (name) => {
    expect(await run(name, form({ id: "../../etc" }))).toStrictEqual({ status: "error", error: "invalid_input", fields: ["id"] });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });
});

describe("replaceAvailabilityRulesAction — decision 1 (replacement of the whole list)", () => {
  it("forwards the parsed list, sorted by weekday then start", async () => {
    await run("replaceAvailabilityRulesAction", form({ rules: JSON.stringify([...aWorkingWeek()].reverse()) }));

    expect(mocks.replaceAvailabilityRules).toHaveBeenCalledWith(aWorkingWeek());
  });

  it("an empty list is forwarded (every rule removed)", async () => {
    await run("replaceAvailabilityRulesAction", form({ rules: "[]" }));

    expect(mocks.replaceAvailabilityRules).toHaveBeenCalledWith([]);
  });

  it.each([
    ["absent", undefined],
    ["not JSON", "{"],
    ["not an array", JSON.stringify(aRule())],
    ["an element without end", JSON.stringify([{ weekday: 1, start: "09:00" }])],
    ["a weekday as text", JSON.stringify([{ weekday: "1", start: "09:00", end: "12:00" }])],
  ])("rules %s → invalid_input ['rules'], before building the container", async (_label, rules) => {
    expect(await run("replaceAvailabilityRulesAction", form({ rules }))).toStrictEqual({
      status: "error",
      error: "invalid_input",
      fields: ["rules"],
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("overlapping or too short rules → invalid_input with the issues of parseAvailabilityRules", async () => {
    const rules = [aRule({ start: "09:00", end: "12:00" }), aRule({ start: "11:00", end: "13:00" }), aRule({ weekday: 2, start: "09:00", end: "09:03" })];

    expect(await run("replaceAvailabilityRulesAction", form({ rules: JSON.stringify(rules) }))).toStrictEqual({
      status: "error",
      error: "invalid_input",
      ruleIssues: [
        { index: 0, reason: "overlap" },
        { index: 1, reason: "overlap" },
        { index: 2, reason: "too_short" },
      ],
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("51 rules → limit_reached, before building the container", async () => {
    const rules = Array.from({ length: 51 }, (_, index) => aRule({ weekday: 1, start: `${String(index % 24).padStart(2, "0")}:00`, end: "23:59" }));

    expect(await run("replaceAvailabilityRulesAction", form({ rules: JSON.stringify(rules) }))).toStrictEqual({
      status: "error",
      error: "limit_reached",
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("0038 point 6: 52 rules (MAX_AVAILABILITY_RULES + 2) whose last one is malformed → limit_reached, not invalid_input", async () => {
    const rules = [
      ...Array.from({ length: 51 }, () => aRule()),
      { weekday: "1", start: "09:00", end: "12:00" },
    ];

    expect(await run("replaceAvailabilityRulesAction", form({ rules: JSON.stringify(rules) }))).toStrictEqual({
      status: "error",
      error: "limit_reached",
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it("0038 point 6: 100 000 malformed elements → limit_reached, before building the container, without a parse per element", async () => {
    const rules = JSON.stringify(Array.from({ length: 100_000 }, (_, index) => ({ weekday: `x${index}`, start: 1, end: null })));

    expect(await run("replaceAvailabilityRulesAction", form({ rules }))).toStrictEqual({ status: "error", error: "limit_reached" });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it.each(["overlap", "limit_reached", "invalid_input"] as const)("use case %s (database refusal) → error %j", async (error) => {
    mocks.replaceAvailabilityRules.mockResolvedValue(err(error));

    expect(await run("replaceAvailabilityRulesAction", form({ rules: JSON.stringify(aWorkingWeek()) }))).toMatchObject({
      status: "error",
      error,
    });
  });
});

describe("addAvailabilityExceptionAction / removeAvailabilityExceptionAction — criterion 1", () => {
  it("forwards id (lower-cased), kind, start and end as submitted (conversion by the use case)", async () => {
    await run("addAvailabilityExceptionAction", form({ ...anExceptionInput(), id: EXCEPTION_IDS[0].toUpperCase() }));

    expect(mocks.addAvailabilityException).toHaveBeenCalledWith(anExceptionInput());
  });

  it("malformed id → invalid_input ['id'] before building the container", async () => {
    expect(await run("addAvailabilityExceptionAction", form({ ...anExceptionInput(), id: "1" }))).toStrictEqual({
      status: "error",
      error: "invalid_input",
      fields: ["id"],
    });
    expect(mocks.createContainer).not.toHaveBeenCalled();
  });

  it.each([
    ["invalid_kind", { status: "error", error: "invalid_input", fields: ["kind"] }],
    ["invalid_start", { status: "error", error: "invalid_input", fields: ["start"] }],
    ["invalid_end", { status: "error", error: "invalid_input", fields: ["end"] }],
    ["invalid_range", { status: "error", error: "invalid_range", fields: ["end"] }],
    ["already_ended", { status: "error", error: "already_ended", fields: ["end"] }],
    ["limit_reached", { status: "error", error: "limit_reached" }],
  ] as const)("use case %s → %j", async (error, state) => {
    mocks.addAvailabilityException.mockResolvedValue(err(error));

    expect(await run("addAvailabilityExceptionAction", form(anExceptionInput()))).toStrictEqual(state);
  });

  it("remove: forwards the id", async () => {
    await run("removeAvailabilityExceptionAction", form({ id: EXCEPTION_IDS[1] }));

    expect(mocks.removeAvailabilityException).toHaveBeenCalledWith(EXCEPTION_IDS[1]);
  });
});
