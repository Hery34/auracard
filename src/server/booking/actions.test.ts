/**
 * Contract frozen by test-engineer (0038, decision 1; ADR 0012 §1: `src/server/booking/actions.ts`, agent scheduling).
 *
 * // src/server/booking/actions.ts — "use server"; only async functions are exported (types aside).
 * export type BookingSettingsActionError =
 *   | "invalid_input" | "not_found" | "rate_limited" | "limit_reached" | "has_bookings" | "overlap" | "conflict"
 *   | "invalid_range" | "already_ended" | "unexpected";
 * export type BookingSettingsState =
 *   | { status: "idle" }
 *   | { status: "saved" }
 *   | { status: "error"; error: BookingSettingsActionError; fields?: string[]; ruleIssues?: RuleIssue[] };
 * // Every action: (previous: BookingSettingsState, formData: FormData) => Promise<BookingSettingsState>.
 * //   Chain: parse the form (before createContainer) → use case of createContainer() (session, profile-write, own
 * //   profile: authorization in every action) → map the Result. Use case "unauthenticated" → redirect("/connexion").
 * //   Success only: revalidatePath("/tableau-de-bord/rendez-vous/reglages") → { status: "saved" }.
 * //   No submitted value is ever echoed in the state.
 * // saveTimeZoneAction            fields: timeZone (validated by the use case; invalid_input → fields ["timeZone"])
 * // createEventTypeAction         fields: id (uuid v4 generated by the form at mount, lower-cased), title, durationMin,
 * // updateEventTypeAction                 bufferMin, minNoticeMin (decimal digits only, else invalid), locationKind,
 * //                                       locationText (absent → null); parsed by parseEventTypeDraft; invalid →
 * //                                       { error: "invalid_input", fields } in the order ["id", ...EVENT_TYPE_FIELDS]
 * // setEventTypeActiveAction      fields: id, isActive ("true" | "false")
 * // reorderEventTypesAction       field ids: JSON array of 1 to 10 uuids, the full order
 * // deleteEventTypeAction         field id
 * // replaceAvailabilityRulesAction field rules: JSON array of { weekday: number, start: string, end: string } (bad
 * //                                       shape → fields ["rules"]); parseAvailabilityRules: "too_many" → limit_reached,
 * //                                       issues → { error: "invalid_input", ruleIssues }. 0038 point 6: the schema
 * //                                       `availabilityRulesSchema` is bounded (.max(MAX_AVAILABILITY_RULES + 1)); a
 * //                                       longer array → limit_reached (not invalid_input), whatever its elements,
 * //                                       before the container and without parsing every element
 * // addAvailabilityExceptionAction fields: id, kind, start, end (datetime-local, converted by the use case);
 * //                                       invalid_kind/start/end → invalid_input with fields ["kind"] / ["start"] /
 * //                                       ["end"]; invalid_range and already_ended kept, with fields ["end"]
 * // removeAvailabilityExceptionAction field id
 *
 * // src/server/container.ts — Container gains getBookingSettings, saveTimeZone, createEventType, updateEventType,
 * // setEventTypeActive, reorderEventTypes, deleteEventType, replaceAvailabilityRules, addAvailabilityException,
 * // removeAvailabilityException (session client repositories, real clock).
 */
