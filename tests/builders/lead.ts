/**
 * `count` leads of one profile, newest first by (createdAt, id): lead `i` is `i` minutes older than lead 0, except
 * that every group of `tie` consecutive leads shares one createdAt (ties broken by id, descending).
 */
export function ownLeads(count: number, options: { tie?: number } = {}): OwnLead[] {
  const tie = options.tie ?? 1;
  return Array.from({ length: count }, (_, index) => {
    const group = Math.floor(index / tie);
    return anOwnLead({
      id: leadId(count - index),
      name: `Visiteur ${index}`,
      email: `visiteur-${index}@example.test`,
      message: `Message ${index}`,
      createdAt: leadTimestamp(group * 60, 123456),
    });
  });
}

