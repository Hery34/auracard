/** `created_at` as PostgREST returns a timestamptz: microseconds, explicit offset. */
export function leadTimestamp(secondsBefore: number, micros = 0): string {
  const base = Date.UTC(2026, 10, 18, 12, 0, 0) - secondsBefore * 1000;
  const iso = new Date(base).toISOString().slice(0, 19);
  return `${iso}.${String(micros).padStart(6, "0")}+00:00`;
}

/** Deterministic uuid v4 numbered `index` (lower case). */
export function leadId(index: number): string {
  return `00000000-0000-4000-8000-${index.toString(16).padStart(12, "0")}`;
}

