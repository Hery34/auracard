/** `[start, end]` as text: Temporal instants are compared through their canonical string, never by `toStrictEqual`. */
export function rangeText(range: TimeRange): [string, string] {
  return [range.start.toString(), range.end.toString()];
}

/** A PostgREST error as returned by `rpc`. */
export function postgrestError(code: string, message = "error"): { code: string; message: string; details: string | null; hint: string | null } {
  return { code, message, details: null, hint: null };
}
